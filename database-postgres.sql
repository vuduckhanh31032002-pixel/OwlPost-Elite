-- =====================================================================
--  OWLPOST ELITE (ChatApp) - CẤU TRÚC CƠ SỞ DỮ LIỆU PostgreSQL
--  Đồ án môn Điện toán di động
-- =====================================================================
--
--  MỤC ĐÍCH CỦA FILE
--  ------------------
--  File này là TÀI LIỆU MÔ TẢ cấu trúc database PostgreSQL đang được
--  ứng dụng sử dụng, dành cho giảng viên tham khảo khi chấm đồ án.
--
--  Nguồn: lấy trực tiếp từ schema thực tế của database runtime
--         `chatapp` (PostgreSQL 16) đang chạy trên localhost:5432.
--
--  LƯU Ý QUAN TRỌNG
--  -----------------
--  * File KHÔNG phải script khởi tạo database. Không cần chạy file này
--    để dựng lại database.
--  * Ứng dụng KHÔNG dùng file SQL này để tạo bảng. Toàn bộ schema
--    được Hibernate tự đồng bộ từ 9 file Entity (@Entity) nhờ cấu hình
--    `spring.jpa.hibernate.ddl-auto=update`.
--  * File chỉ nhằm GIẢI THÍCH cấu trúc: bảng, cột, kiểu dữ liệu,
--    khóa chính, khóa ngoại, ràng buộc và index.
--  * Không có dữ liệu (không có INSERT), không có mật khẩu, không có
--    lệnh quản trị, không có CREATE DATABASE / DROP / USE.
--
--  NGUYÊN TẮC
--  ----------
--  Nội dung dưới đây mô tả ĐÚNG database đang chạy:
--    - Không thêm cột nào
--    - Không bỏ cột nào
--    - Không đổi tên bảng / cột
--    - Không tự thêm khóa ngoại, ràng buộc hoặc index
--    - Giữ nguyên cả những cột có kiểu varchar rất lớn
--
-- =====================================================================
--  TỔNG QUAN: 8 bảng được ứng dụng sử dụng
-- ---------------------------------------------------------------------
--   users         : người dùng
--   chatrooms     : phòng chat (riêng tư và nhóm)
--   roommembers   : thành viên của phòng (quan hệ n-n, có soft delete)
--   messages      : tin nhắn
--   friends       : quan hệ bạn bè (quan hệ n-n)
--   friendrequests: lời mời kết bạn
--   groupinvites  : lời mời vào nhóm
--   blocked_users : danh sách chặn người dùng
--
--  Quan hệ tổng thể:
--      users  1 ──< n  roommembers  >── 1  chatrooms
--      users  1 ──< n  messages     >── 1  chatrooms
--      messages tự tham chiếu (replytoid) cho tin nhắn trả lời
--      users  n ──< n  friends / friendrequests / blocked_users
--      chatrooms 1 ──< n  groupinvites >── n  users
-- =====================================================================


-- =====================================================================
--  1. users - BẢNG NGƯỜI DÙNG
-- =====================================================================
--  Ứng dụng tạo tài khoản qua đăng ký thường hoặc đăng nhập Google
--  (cột authprovider lưu "GOOGLE" cho tài khoản Google).
--  Cột password được mã hóa BCrypt và không bao giờ gửi ra frontend.
-- =====================================================================

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(100) NOT NULL,
    password      VARCHAR(255) NOT NULL,
    fullname      VARCHAR(100) NOT NULL,
    username      VARCHAR(100),
    phonenumber   VARCHAR(30),
    dayofbirth    VARCHAR(32),
    monthofbirth  VARCHAR(32),
    yearofbirth   VARCHAR(255),
    avatar        VARCHAR(2000000),
    authprovider  VARCHAR(20),
    createdat     TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT users_pkey PRIMARY KEY (id),
    -- Chặn trùng email: mỗi tài khoản một email duy nhất
    CONSTRAINT ukncoa9bfasrql0x4nhmh1plxxy UNIQUE (email)
);


-- =====================================================================
--  2. chatrooms - BẢNG PHÒNG CHAT
-- =====================================================================
--  Dùng chung cho cả chat riêng tư (isprivate = true) và nhóm
--  (isprivate = false). Phân biệt bằng cột isprivate.
--  groupname chỉ dùng cho phòng nhóm.
--  groupAvatar / groupBackground lưu ảnh và ảnh bìa nhóm (dạng TEXT,
--  có thể chứa cả chuỗi data URL base64).
-- =====================================================================

CREATE TABLE chatrooms (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    isprivate        BOOLEAN,
    groupname        VARCHAR(255),
    "groupAvatar"     TEXT,
    "groupBackground" TEXT,
    avatar           VARCHAR(255),
    background       VARCHAR(255),
    createdat        TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT chatrooms_pkey PRIMARY KEY (id)
);


-- =====================================================================
--  3. roommembers - BẢNG THÀNH VIÊN PHÒNG CHAT
-- =====================================================================
--  Bảng trung gian cho quan hệ n-n giữa users và chatrooms.
--  Khóa chính tổ hợp (roomid, userid) ngăn một người vào phòng 2 lần.
--  deleted = TRUE nghĩa là người dùng đã xóa cuộc trò chuyện khỏi
--  danh sách của họ (soft delete) -> vẫn có thể khôi phục.
--  Lưu ý: cột deleted cho phép NULL trong runtime.
-- =====================================================================

CREATE TABLE roommembers (
    roomid   BIGINT      NOT NULL,
    userid   BIGINT      NOT NULL,
    deleted  BOOLEAN     DEFAULT false,

    CONSTRAINT roommembers_pkey PRIMARY KEY (roomid, userid)
);

ALTER TABLE ONLY roommembers
    ADD CONSTRAINT fkm4oppxdar0mgfc8agiu8bwfge
    FOREIGN KEY (roomid) REFERENCES chatrooms (id);

ALTER TABLE ONLY roommembers
    ADD CONSTRAINT fk1knqgdknev5pybji2qpuaskok
    FOREIGN KEY (userid) REFERENCES users (id);


-- =====================================================================
--  4. messages - BẢNG TIN NHẮN
-- =====================================================================
--  content và imageurl dùng kiểu TEXT vì hình ảnh/video được lưu trực
--  tiếp dưới dạng chuỗi base64 (giới hạn 50MB ở tầng frontend).
--  replytoid cho phép trả lời một tin nhắn (tự tham chiếu cùng bảng).
--  Lưu ý: pinned và unsent là cột boolean NOT NULL nhưng KHÔNG có
--  DEFAULT trong runtime.
-- =====================================================================

CREATE TABLE messages (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    roomid     BIGINT,
    senderid   BIGINT,
    content    TEXT,
    imageurl   TEXT,
    senttime   TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    replytoid  BIGINT,
    pinned     BOOLEAN      NOT NULL,
    unsent     BOOLEAN      NOT NULL,

    CONSTRAINT messages_pkey PRIMARY KEY (id)
);

ALTER TABLE ONLY messages
    ADD CONSTRAINT fkmvr6xye6n9cu33hm1is2c2xg0
    FOREIGN KEY (roomid) REFERENCES chatrooms (id);

ALTER TABLE ONLY messages
    ADD CONSTRAINT fksiwxkpqjd7vxm7rlcufmbfygr
    FOREIGN KEY (senderid) REFERENCES users (id);

-- Tự tham chiếu: tin nhắn được trả lời
ALTER TABLE ONLY messages
    ADD CONSTRAINT fkkitl1b7r1bpn5v3n6m09w1ioa
    FOREIGN KEY (replytoid) REFERENCES messages (id);


-- =====================================================================
--  5. friends - BẢNG BẠN BÈ
-- =====================================================================
--  Quan hệ n-n, dữ liệu được lưu HAI CHIỀU:
--  khi A kết bạn với B, hệ thống ghi 2 bản ghi (A,B) và (B,A).
--  Khóa chính tổ hợp ngăn ghi trùng cặp.
--  Ghi chú: runtime KHÔNG có khóa ngoại cho bảng này, và tên cột
--  trong runtime là friendid / userid (không phân biệt chữ hoa).
-- =====================================================================

CREATE TABLE friends (
    userid     BIGINT      NOT NULL,
    friendid   BIGINT      NOT NULL,
    createdat  TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT friends_pkey PRIMARY KEY (friendid, userid)
);


-- =====================================================================
--  6. friendrequests - BẢNG LỜI MỜI KẾT BẠN
-- =====================================================================
--  status lưu PENDING / ACCEPTED / REJECTED.
--  senderid là người gửi, receiverid là người nhận.
--  Khi người nhận đồng ý, hệ thống tự tạo phòng chat riêng tư.
-- =====================================================================

CREATE TABLE friendrequests (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    senderid    BIGINT,
    receiverid  BIGINT,
    status      VARCHAR(20),
    createdat   TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT friendrequests_pkey PRIMARY KEY (id)
);

ALTER TABLE ONLY friendrequests
    ADD CONSTRAINT fkn1s8r5mcbpklhe69stqa9v2c1
    FOREIGN KEY (senderid) REFERENCES users (id);

ALTER TABLE ONLY friendrequests
    ADD CONSTRAINT fkojgeyd2xmglek2n5995b8k03v
    FOREIGN KEY (receiverid) REFERENCES users (id);


-- =====================================================================
--  7. groupinvites - BẢNG LỜI MỜI VÀO NHÓM
-- =====================================================================
--  Khi người dùng tạo nhóm, hệ thống tạo phòng và gửi lời mời cho
--  từng thành viên được chọn. Chỉ khi người nhận đồng ý thì mới
--  ghi thêm vào roommembers.
--  status lưu PENDING / ACCEPTED / REJECTED.
-- =====================================================================

CREATE TABLE groupinvites (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    roomid      BIGINT       NOT NULL,
    senderid    BIGINT       NOT NULL,
    receiverid  BIGINT       NOT NULL,
    status      VARCHAR(255),
    createdat   TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT groupinvites_pkey PRIMARY KEY (id)
);

ALTER TABLE ONLY groupinvites
    ADD CONSTRAINT fkqmicsywehjtgvhp5j32cdd0u7
    FOREIGN KEY (roomid) REFERENCES chatrooms (id);

ALTER TABLE ONLY groupinvites
    ADD CONSTRAINT fkpi7qa96b1e1xgmr7k836gqbfd
    FOREIGN KEY (senderid) REFERENCES users (id);

ALTER TABLE ONLY groupinvites
    ADD CONSTRAINT fk56uukcio7olgruo5vxlnhe3ua
    FOREIGN KEY (receiverid) REFERENCES users (id);


-- =====================================================================
--  8. blocked_users - BẢNG CHẶN NGƯỜI DÙNG
-- =====================================================================
--  Ghi nhận quan hệ "blocker_id chặn blocked_id".
--  Khi hai bên có quan hệ chặn theo bất kỳ chiều nào, ứng dụng không
--  cho gửi tin nhắn vào phòng chứa cả hai người.
--  Ghi chú: runtime KHÔNG có khóa ngoại và KHÔNG có ràng buộc UNIQUE
--  cho cặp (blocker_id, blocked_id).
-- =====================================================================

CREATE TABLE blocked_users (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    blocker_id  BIGINT  NOT NULL,
    blocked_id  BIGINT  NOT NULL,

    CONSTRAINT blocked_users_pkey PRIMARY KEY (id)
);


-- =====================================================================
--  TỔNG KẾT INDEX ĐANG TỒN TẠI TRONG RUNTIME
-- ---------------------------------------------------------------------
--  Database hiện có đúng 9 index, tất cả đều do Hibernate tự sinh ra
--  từ khóa chính và ràng buộc UNIQUE:
--
--    blocked_users_pkey                              UNIQUE (id)
--    chatrooms_pkey                                  UNIQUE (id)
--    friendrequests_pkey                             UNIQUE (id)
--    friends_pkey                                    UNIQUE (friendid, userid)
--    groupinvites_pkey                               UNIQUE (id)
--    messages_pkey                                   UNIQUE (id)
--    roommembers_pkey                                UNIQUE (roomid, userid)
--    ukncoa9bfasrql0x4nhmh1plxxy                    UNIQUE (email)  trên users
--    users_pkey                                      UNIQUE (id)
--
--  Ghi chú: runtime KHÔNG có index phụ riêng cho các cột
--  messages(roomid), messages(senderid), roommembers(userid),
--  friends(userid). Với khối lượng dữ liệu hiện tại (vài trăm tin
--  nhắn) thì vẫn đápứng tốt; khi dữ liệu lớn lên sẽ cần bổ sung.
--
--  Ghi chú: runtime KHÔNG có CHECK constraint nào.
--  Ghi chú: khóa ngoại trong runtime không khai báo ON DELETE CASCADE
--  (do Hibernate tạo mặc định), nên xóa người dùng hoặc phòng phải
--  được thực hiện qua tầng service.
-- =====================================================================