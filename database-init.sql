-- ---------------------------------------------------------------------
--  EXTENSION unaccent
--  Dùng cho chức năng tìm kiếm người dùng không dấu
--  (ví dụ gõ "Khanh" vẫn tìm thấy "Khánh").
--  Nếu lệnh này báo lỗi do thiếu quyền, bạn có thể bỏ qua:
--  ứng dụng vẫn chạy, chỉ là tìm kiếm sẽ không bỏ qua dấu.
-- ---------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS unaccent;


-- ---------------------------------------------------------------------
--  1. users - người dùng
--  password được mã hóa BCrypt, không bao giờ gửi ra frontend.
--  authprovider = "GOOGLE" cho tài khoản đăng nhập bằng Google.
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(100) NOT NULL,
    password      VARCHAR(255) NOT NULL,
    fullname      VARCHAR(100) NOT NULL,
    username      VARCHAR(100),
    phonenumber   VARCHAR(30),
    dayofbirth    VARCHAR(32),
    monthofbirth  VARCHAR(32),
    yearofbirth   VARCHAR(255),
    avatar        VARCHAR(2000000),
    authprovider  VARCHAR(20),
    createdat     TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email)
);


-- ---------------------------------------------------------------------
--  2. chatrooms - phòng chat
--  Dùng chung cho chat riêng tư (isprivate = TRUE) và nhóm (FALSE).
-- ---------------------------------------------------------------------
CREATE TABLE chatrooms (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    isprivate        BOOLEAN,
    groupname        VARCHAR(255),
    "groupAvatar"     TEXT,
    "groupBackground" TEXT,
    avatar           VARCHAR(255),
    background       VARCHAR(255),
    createdat        TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT chatrooms_pkey PRIMARY KEY (id)
);


-- ---------------------------------------------------------------------
--  3. roommembers - thành viên phòng chat (quan hệ n-n)
--  deleted = TRUE nghĩa là người dùng đã xóa cuộc trò chuyện khỏi
--  danh sách của họ (soft delete) -> vẫn khôi phục được.
-- ---------------------------------------------------------------------
CREATE TABLE roommembers (
    roomid   BIGINT      NOT NULL,
    userid   BIGINT      NOT NULL,
    deleted  BOOLEAN     DEFAULT false,

    CONSTRAINT roommembers_pkey PRIMARY KEY (roomid, userid)
);

ALTER TABLE ONLY roommembers
    ADD CONSTRAINT fk_roommembers_room
    FOREIGN KEY (roomid) REFERENCES chatrooms (id);

ALTER TABLE ONLY roommembers
    ADD CONSTRAINT fk_roommembers_user
    FOREIGN KEY (userid) REFERENCES users (id);


-- ---------------------------------------------------------------------
--  4. messages - tin nhắn
--  content / imageurl dùng kiểu TEXT vì ảnh và video được lưu trực
--  tiếp dưới dạng chuỗi base64.
--  replytoid cho phép trả lời một tin nhắn (tự tham chiếu cùng bảng).
-- ---------------------------------------------------------------------
CREATE TABLE messages (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    roomid     BIGINT,
    senderid   BIGINT,
    content    TEXT,
    imageurl   TEXT,
    senttime   TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    replytoid  BIGINT,
    pinned     BOOLEAN      NOT NULL,
    unsent     BOOLEAN      NOT NULL,

    CONSTRAINT messages_pkey PRIMARY KEY (id)
);

ALTER TABLE ONLY messages
    ADD CONSTRAINT fk_messages_room
    FOREIGN KEY (roomid) REFERENCES chatrooms (id);

ALTER TABLE ONLY messages
    ADD CONSTRAINT fk_messages_user
    FOREIGN KEY (senderid) REFERENCES users (id);

ALTER TABLE ONLY messages
    ADD CONSTRAINT fk_messages_replyto
    FOREIGN KEY (replytoid) REFERENCES messages (id);


-- ---------------------------------------------------------------------
--  5. friends - bạn bè (quan hệ n-n)
--  Lưu HAI CHIỀU: kết bạn A với B sẽ tạo 2 bản ghi (A,B) và (B,A).
--  Lưu ý: bảng này không có khóa ngoại, giống hệt cấu trúc đang chạy.
-- ---------------------------------------------------------------------
CREATE TABLE friends (
    userid     BIGINT      NOT NULL,
    friendid   BIGINT      NOT NULL,
    createdat  TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT friends_pkey PRIMARY KEY (friendid, userid)
);


-- ---------------------------------------------------------------------
--  6. friendrequests - lời mời kết bạn
--  status: PENDING / ACCEPTED / REJECTED
-- ---------------------------------------------------------------------
CREATE TABLE friendrequests (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    senderid    BIGINT,
    receiverid  BIGINT,
    status      VARCHAR(20),
    createdat   TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT friendrequests_pkey PRIMARY KEY (id)
);

ALTER TABLE ONLY friendrequests
    ADD CONSTRAINT fk_friendrequests_sender
    FOREIGN KEY (senderid) REFERENCES users (id);

ALTER TABLE ONLY friendrequests
    ADD CONSTRAINT fk_friendrequests_receiver
    FOREIGN KEY (receiverid) REFERENCES users (id);


-- ---------------------------------------------------------------------
--  7. groupinvites - lời mời vào nhóm
--  status: PENDING / ACCEPTED / REJECTED
-- ---------------------------------------------------------------------
CREATE TABLE groupinvites (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    roomid      BIGINT       NOT NULL,
    senderid    BIGINT       NOT NULL,
    receiverid  BIGINT       NOT NULL,
    status      VARCHAR(255),
    createdat   TIMESTAMP(6) WITHOUT TIME ZONE,

    CONSTRAINT groupinvites_pkey PRIMARY KEY (id)
);

ALTER TABLE ONLY groupinvites
    ADD CONSTRAINT fk_groupinvites_room
    FOREIGN KEY (roomid) REFERENCES chatrooms (id);

ALTER TABLE ONLY groupinvites
    ADD CONSTRAINT fk_groupinvites_sender
    FOREIGN KEY (senderid) REFERENCES users (id);

ALTER TABLE ONLY groupinvites
    ADD CONSTRAINT fk_groupinvites_receiver
    FOREIGN KEY (receiverid) REFERENCES users (id);


-- ---------------------------------------------------------------------
--  8. blocked_users - chặn người dùng
--  Ghi nhận quan hệ "blocker_id chặn blocked_id". Khi hai bên có quan
--  hệ chặn theo bất kỳ chiều nào, ứng dụng không cho gửi tin nhắn
--  vào phòng chứa cả hai người.
--  Lưu ý: bảng này không có khóa ngoại và không có UNIQUE cho cặp
--  (blocker_id, blocked_id) — giống hệt cấu trúc đang chạy.
-- ---------------------------------------------------------------------
CREATE TABLE blocked_users (
    id          BIGINT  GENERATED BY DEFAULT AS IDENTITY,
    blocker_id  BIGINT  NOT NULL,
    blocked_id  BIGINT  NOT NULL,

    CONSTRAINT blocked_users_pkey PRIMARY KEY (id)
);


