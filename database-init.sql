--  ---- CÁCH 1: dùng psql (khuyến nghị) -----------------------------------
--      psql -U postgres -c "CREATE DATABASE chatapp;"
--
--  ---- CÁCH 2: dùng pgAdmin ---------------------------------------------
--      Mở Query Tool, CHỈ chạy đúng một dòng:
--          CREATE DATABASE chatapp;
--      (đừng bấm chạy cả file)
--
--  ---- CÁCH 3: dùng DBeaver / công cụ SQL khác -------------------------
--      Tạo database "chatapp" bằng thao tác Create Database trên giao
--      diện, hoặc chạy riêng câu lệnh trên.
--
--  ---- NẾU DATABASE "chatapp" ĐÃ TỒN TẠI -------------------------------
--      Bỏ qua bước này. File này KHÔNG dùng lệnh DROP DATABASE nên
